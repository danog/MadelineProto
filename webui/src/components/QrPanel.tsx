import { useEffect, useState } from "react";
import { useStrings } from "../strings";

export type QrState = { status: "loading" } | { status: "waiting"; svg: string } | { status: "done"; svg: string | null };

interface QrResponse {
    logged_in: boolean;
    svg?: string;
}

/**
 * Long-poll the QR code login endpoint of the script (Wrappers\Start::webQrLogin): `getQrCode` returns the
 * current QR code, `waitQrCodeOrLogin` returns within 5 seconds with a new QR code (the previous one expired)
 * or with `logged_in` (scanned, or the login moved on to the password).
 */
export function useQrLogin(endpoint: string, onLoggedIn: () => void, retryDelay = 1000): QrState {
    const [state, setState] = useState<QrState>({ status: "loading" });
    useEffect(() => {
        const controller = new AbortController();
        let timer: ReturnType<typeof setTimeout> | undefined;
        let failures = 0;
        let svg: string | null = null;
        // The response is injected as markup: only ever ask the script that served the page
        const url = new URL(endpoint, window.location.href);
        if (url.origin !== window.location.origin) {
            return;
        }
        // Absolute: a path starting with // (https://host//evil.example/) would be a protocol-relative URL
        const base = url.origin + url.pathname;
        const poll = (query: "getQrCode" | "waitQrCodeOrLogin") => {
            fetch(`${base}?${query}`, { credentials: "same-origin", cache: "no-store", redirect: "error", signal: controller.signal })
                .then((response) => {
                    if (!response.ok) {
                        throw new Error(`HTTP ${response.status}`);
                    }
                    return response.json() as Promise<QrResponse>;
                })
                .then((result) => {
                    failures = 0;
                    if (result.logged_in) {
                        setState({ status: "done", svg });
                        onLoggedIn();
                        return;
                    }
                    svg = result.svg ?? "";
                    setState({ status: "waiting", svg });
                    poll("waitQrCodeOrLogin");
                })
                .catch(() => {
                    if (controller.signal.aborted) {
                        return;
                    }
                    // The server or the connection is down: back off, and get a fresh code after repeated failures
                    failures++;
                    timer = setTimeout(() => poll(failures > 1 ? "getQrCode" : "waitQrCodeOrLogin"), Math.min(retryDelay * failures, 10 * retryDelay));
                });
        };
        poll("getQrCode");
        return () => {
            controller.abort();
            clearTimeout(timer);
        };
    }, [endpoint, onLoggedIn, retryDelay]);
    return state;
}

/** Reload the page with a GET request (a reload could submit a POST again). */
export function reloadPage(): void {
    window.location.href = window.location.href.split("#")[0];
}

/** The QR code login panel, once the first QR code arrived. */
export function QrPanel({ state }: { state: Exclude<QrState, { status: "loading" }> }) {
    const t = useStrings();
    const done = state.status === "done";
    return (
        <section className={`qr${done ? " is-done" : ""}`} aria-labelledby="qr-title">
            <h2 id="qr-title">{t("webQrTitle")}</h2>
            <div className="qr-frame">
                {/* The SVG is generated by MadelineProto from the login token, on the same origin */}
                <div className="qr-code" role="img" aria-label={t("webQrTitle")} dangerouslySetInnerHTML={{ __html: state.svg ?? "" }} />
            </div>
            <p className="qr-status" aria-live="polite">
                <span className="qr-pulse" aria-hidden="true" />
                <span>{t(done ? "loginQrCodeSuccessful" : "webQrWaiting")}</span>
            </p>
            <ol className="qr-steps">
                <li>{t("loginWebQr1")}</li>
                <li>{t("loginWebQr2")}</li>
                <li>{t("loginWebQr3")}</li>
            </ol>
        </section>
    );
}
